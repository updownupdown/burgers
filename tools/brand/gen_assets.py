"""Writes every Bun Voyage logo asset from one place (DESIGN §44).

    pip install uharfbuzz fonttools      # once
    python3 tools/brand/gen_assets.py    # rewrites the files below
    node pwa/make-icons.cjs              # then rasterises the icons and favicons to PNG

Writes:
  src/ui/logo-art.ts       the outlined lockups (stacked and one line) for src/ui/logo.ts
  public/logo-*.svg        the same lockups as files, slate and paper colourways, and the ink mark
  public/favicon.svg       the mark drawn for 32 to 48 px, on a slate tile
  pwa/favicon-16.svg       the mark drawn for 16 px (rendered to public/favicon-16.png)
  pwa/icon.svg             the 'any' and Apple icon (512)
  pwa/icon-maskable.svg    the maskable icon, filling Android's safe zone
  pwa/icon-monochrome.svg  the themed (Android 13+) icon, white on transparent
  index.html               the splash wordmark, between the bv:wordmark markers

The wordmark is Young Serif (tools/brand/font, OFL) shaped with its own kerning plus two pair
tweaks, then outlined, so nothing in the logo waits for a web font.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
import brand as B  # noqa: E402

VOY_NIGHT = '#f2c262'   # Voyage on slate: the header's butter (--bv-logo-voyage)
VOY_PAPER = '#a37419'   # Voyage on cream: butter deepened to 3.6:1 (--bv-logo-voyage-paper)
INK = B.INK             # mark and Bun on cream
SLATE = B.SLATE
CREAM = B.CREAM

# Sentinel colours, swapped for classes in the inline (themeable) version.
S_MARK, S_KNOB, S_BUN, S_VOY = '#000001', '#000002', '#000003', '#000004'


def write(rel, s):
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w') as f:
        f.write(s if s.endswith('\n') else s + '\n')
    print('wrote', rel)


def colour(svg, mark, knob, bun, voy):
    return svg.replace(S_MARK, mark).replace(S_KNOB, knob).replace(S_BUN, bun).replace(S_VOY, voy)


def classed(svg):
    """Inline version: each part gets a class (src/ui/logo.css colours it) and keeps the slate fill."""
    svg = svg.replace(f'stroke="{S_MARK}"', f'class="lg-m" stroke="{CREAM}"')
    svg = svg.replace(f'fill="{S_KNOB}"', 'class="lg-k" fill="#ffffff"')
    svg = svg.replace(f'fill="{S_BUN}"', f'class="lg-b" fill="{CREAM}"')
    svg = svg.replace(f'fill="{S_VOY}"', f'class="lg-v" fill="{VOY_NIGHT}"')
    return svg


def vbs(vb):
    return ' '.join(f'{v:.0f}' if abs(v - round(v)) < 1e-6 else f'{v:.1f}' for v in vb)


SENT = dict(c_bun=S_BUN, c_voy=S_VOY, c_mark=S_MARK, c_knob=S_KNOB)

# ---- Lockups ---------------------------------------------------------------------------------
# Stacked (the map header): plate on Voyage's baseline, knob just under Bun's cap height, the
# mark's stroke equal to the serif's stem.
stack, stack_vb, stack_info = B.lockup_stack(gap=340, mark_scale=0.92, **SENT)
# One line (welcome card, Settings, share card): the compact mark, heavier, so it holds at 13 px.
line, line_vb, line_info = B.lockup_line(**SENT)
# Round the boxes out to whole units so the SVG edges don't clip a curve.
stack_vb = (0, round(stack_vb[1]), round(stack_vb[2] + 0.5), round(stack_vb[3] + 0.5))
line_vb = (0, round(line_vb[1]), round(line_vb[2] + 0.5), round(line_vb[3] + 0.5))

art = {
    'stack': {'viewBox': vbs(stack_vb), 'w': stack_vb[2], 'h': stack_vb[3], 'svg': classed(stack)},
    'line': {'viewBox': vbs(line_vb), 'w': line_vb[2], 'h': line_vb[3], 'svg': classed(line)},
}
ts = ['// Generated by tools/brand/gen_assets.py; do not edit by hand. Outlined Young Serif, see DESIGN §44.',
      '// Each part carries a class (lg-m mark stroke, lg-k knob, lg-b "Bun", lg-v "Voyage") for src/ui/logo.css.']
for k, v in art.items():
    ts.append(f'export const {k.upper()} = {json.dumps(v)} as const;')
write('src/ui/logo-art.ts', '\n'.join(ts))

for name, inner, vb in (('logo-lockup', stack, stack_vb), ('logo-line', line, line_vb)):
    write(f'public/{name}.svg', B.svg_doc(colour(inner, CREAM, '#ffffff', CREAM, VOY_NIGHT), vb))
    write(f'public/{name}-paper.svg', B.svg_doc(colour(inner, INK, INK, INK, VOY_PAPER), vb))

# The ink cut of the mark: the kit drawing (public/logo.svg) with the knob in ink too, for cream.
write('public/logo-ink.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">\n'
      '  <!-- Bun Voyage mark for cream (paper) surfaces: public/logo.svg in ink, knob included. -->\n'
      f'  {B.mark_g(color=INK, knob=INK)}\n</svg>')

# ---- Favicons: one drawing per size ---------------------------------------------------------
# 16 px: drawn on a 16 grid, whole-pixel 2 px strokes, the rim folded into the dome, open gaps.
write('pwa/favicon-16.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">\n'
      '  <!-- Favicon drawn for 16 px (public/favicon-16.png): whole-pixel 2 px strokes, no rim, open gaps. -->\n'
      f'  <rect width="16" height="16" rx="3.5" fill="{SLATE}"/>'
      f'<path d="M8 6a4 4 0 0 1 4 4H4a4 4 0 0 1 4-4z" fill="none" stroke="{CREAM}" stroke-width="2" stroke-linejoin="round"/>'
      f'<path d="M3 13h10" stroke="{CREAM}" stroke-width="2" stroke-linecap="round"/>'
      '<circle cx="8" cy="3" r="1.3" fill="#fff"/>\n</svg>')
# 32 to 48 px (and the SVG browsers scale up): heavier stroke, plate dropped, knob raised.
write('public/favicon.svg', '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">\n'
      '  <!-- Favicon drawn for 32 to 48 px (public/favicon-32.png): stroke 2.1, plate dropped and knob raised so the gaps hold.\n'
      '       The 16 px cut is pwa/favicon-16.svg. Generated by tools/brand/gen_assets.py. -->\n'
      f'  <rect width="24" height="24" rx="5.5" fill="{SLATE}"/>\n'
      '  <g transform="translate(12 12.4) scale(.84) translate(-12 -11)">'
      + B.mark_g(sw=2.1, knob_r=1.55, knob_cy=3.2, plate_y=18.9) + '</g>\n</svg>')


# ---- App icons ------------------------------------------------------------------------------
# Optically centred: the mark's ink box (knob top 2.1 to plate bottom 19 on the 24 grid) centres
# 2 px below the tile's middle, so the base line doesn't look low. Stroke 2.0 for launcher sizes.
ICON_MARK = dict(sw=2, knob_r=1.5, knob_cy=3.6, plate_y=18)
BODY_CY = 10.55  # (2.1 + 19) / 2


def icon(scale, bg=SLATE, mark=CREAM, knob='#ffffff', note=''):
    rect = f'<rect width="512" height="512" fill="{bg}"/>' if bg else ''
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">'
            + (f'<!-- {note} -->' if note else '') + rect
            + f'<g transform="translate(256 258) scale({scale}) translate(-12 -{BODY_CY})">'
            + B.mark_g(color=mark, knob=knob, **ICON_MARK) + '</g></svg>')


# 'any' and Apple: the mark 58% of the tile, square tile (iOS and launchers round it).
write('pwa/icon.svg', icon(17.5, note='App icon (any, Apple): generated by tools/brand/gen_assets.py; node pwa/make-icons.cjs renders it.'))
# Maskable: 56% of the tile, as large as fits inside the 80% safe circle (r 204.8) with a margin.
MASK = 16
x0, y0, x1, y1 = B.mark_ink(**ICON_MARK)
far = max(((x - 12) * MASK) ** 2 + (2 + (y - BODY_CY) * MASK) ** 2 for x in (x0, x1) for y in (y0, y1)) ** 0.5
assert far < 204.8, far
write('pwa/icon-maskable.svg', icon(MASK, note=f'Maskable icon: the mark reaches {far:.0f} of the 204.8 safe radius.'))
write('pwa/icon-monochrome.svg', icon(MASK, bg=None, mark='#ffffff', note='Themed icon (Android 13+): only the alpha is used.'))

# ---- Splash wordmark in index.html ------------------------------------------------------------
dB, aB = B.text_path('Bun', 0, 750, B.VOY_TWEAKS, B.VOY_TRACK)
dV, aV = B.text_path('Voyage', 0, 750, B.VOY_TWEAKS, B.VOY_TRACK)
sp = 250 + B.VOY_TRACK
W = round(aB + sp + aV)
word = (f'<svg class="sp-word" viewBox="0 -10 {W} 975" role="img" aria-label="Bun Voyage">'
        f'<path d="{dB}" fill="{CREAM}"/><path d="{dV}" transform="translate({aB + sp:.0f} 0)" fill="{VOY_NIGHT}"/></svg>')
idx = os.path.join(ROOT, 'index.html')
html = open(idx).read()
new, n = re.subn(r'(<!--bv:wordmark-->).*?(<!--/bv:wordmark-->)', lambda m: m.group(1) + word + m.group(2), html, flags=re.S)
if n:
    write('index.html', new.rstrip('\n'))
else:
    print('index.html has no bv:wordmark markers; splash wordmark not written')
print('stack', stack_vb, {k: round(v, 1) for k, v in stack_info.items()})
print('line', line_vb, {k: round(v, 1) for k, v in line_info.items()})
